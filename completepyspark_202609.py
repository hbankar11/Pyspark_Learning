"""OR"""
empDF.join(deptDF,empDF.emp_dept_id == deptDF.dept_id,"inner").show(truncate=False)

#Left Join - Return all rows from left dataframe and only matching data from right dataframe
empDF.alias("e").join(deptDF.alias("d"),col("e.emp_dept_id") == col("d.dept_id"),"left").show(truncate=False)
"""OR"""
empDF.join(deptDF,empDF.emp_dept_id == deptDF.dept_id,"left").show(truncate=False)
"""OR"""
empDF.alias("e").join(deptDF.alias("d"),col("e.emp_dept_id") == col("d.dept_id"),"leftouter").show(truncate=False)
"""OR"""
empDF.join(deptDF,empDF.emp_dept_id == deptDF.dept_id,"leftouter").show(truncate=False)
# Right Join - Return all rows from right dataframe and only matching data from left dataframe
empDF.alias("e").join(deptDF.alias("d"),col("e.emp_dept_id") == col("d.dept_id"),"right").show(truncate=False)
